"""Optional report-quality PNG exports from analysis/summary.csv."""

import argparse
import csv
import math
from pathlib import Path
import textwrap


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("summary", help="summary.csv generated by tools/analyze.py")
    p.add_argument("--output", default="results/plots")
    p.add_argument("--title", default="Measured UDP / TCP comparison")
    args = p.parse_args(argv)
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        p.error(
            "Optional dependency missing: sudo apt install python3-matplotlib (SVG plots need no packages)"
        )
    with Path(args.summary).open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        p.error("Summary contains no rows")
    groups = sorted({(r["condition"], r["file"]) for r in rows})
    lookup = {(r["protocol"], r["condition"], r["file"]): r for r in rows}
    out = Path(args.output)
    out.mkdir(parents=True, exist_ok=True)
    for key, ylabel, filename in [
        ("mean_goodput_mbps", "Useful throughput (Mbit/s)", "throughput.png"),
        ("mean_elapsed_s", "Completion time (seconds)", "completion-time.png"),
        (
            "mean_retransmissions",
            "Repeated UDP DATA packets (TCP unavailable)",
            "retransmissions.png",
        ),
    ]:
        fig, ax = plt.subplots(figsize=(max(9, len(groups) * 1.25), 5.5))
        for offset, protocol, color in [
            (-0.19, "udp", "#0284c7"),
            (0.19, "tcp", "#059669"),
        ]:
            values = []
            for condition, file in groups:
                raw = lookup.get((protocol, condition, file), {}).get(key, "")
                values.append(float(raw) if raw else math.nan)
            x = [i + offset for i in range(len(groups))]
            bars = ax.bar(x, values, width=0.36, color=color, label=protocol.upper())
            for xpos, value in zip(x, values):
                if math.isnan(value):
                    ax.annotate("N/A", (xpos, 0), ha="center", va="bottom", fontsize=8)
            ax.bar_label(bars, fmt="%.3g", padding=3, fontsize=8)
        ax.set_xticks(
            range(len(groups)),
            ["\n".join(textwrap.wrap(c + " / " + f, 32)) for c, f in groups],
            fontsize=8,
        )
        ax.set_ylabel(ylabel)
        ax.set_title(args.title)
        ax.legend()
        ax.grid(axis="y", alpha=0.2)
        ax.set_axisbelow(True)
        ax.margins(y=0.15)
        fig.text(
            0.01,
            0.01,
            "Successful-run means; inspect summary.csv for sample counts, failures and dispersion.",
            fontsize=8,
        )
        fig.tight_layout(rect=(0, 0.05, 1, 1))
        fig.savefig(out / filename, dpi=180)
        plt.close(fig)
    print(f"PNG plots written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
